#!/usr/bin/env python3
"""Generate App/data/students_table.c from tools/students.csv.

CSV columns: uid, student_id, name
  uid         hex, 8 chars (4-byte UID) or 14 chars (7-byte UID)
  student_id  1..11 printable ASCII characters
  name        1..20 printable ASCII characters (OLED font is ASCII only)

The table is sorted by (UID length, UID bytes) to match the binary search in
App/services/students.c. Exits with status 1 and a message on any error.

Usage: gen_students.py <students.csv> <students_table.c>
"""
import csv
import sys

UID_HEX_LENGTHS = (8, 14)
STUDENT_ID_MAX = 11
NAME_MAX = 20


def fail(msg):
    print(f"gen_students.py: error: {msg}", file=sys.stderr)
    sys.exit(1)


def printable_ascii(s):
    return all(0x20 <= ord(c) <= 0x7E for c in s)


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load(path):
    rows = []
    seen = set()
    with open(path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        missing = {"uid", "student_id", "name"} - set(reader.fieldnames or [])
        if missing:
            fail(f"{path}: missing column(s): {', '.join(sorted(missing))}")
        for line_no, row in enumerate(reader, start=2):
            uid = (row["uid"] or "").strip().upper()
            sid = (row["student_id"] or "").strip()
            name = (row["name"] or "").strip()
            if not uid and not sid and not name:
                continue  # blank line
            where = f"{path}:{line_no}"
            if len(uid) not in UID_HEX_LENGTHS:
                fail(f"{where}: uid '{uid}' must be 8 or 14 hex characters")
            try:
                uid_bytes = bytes.fromhex(uid)
            except ValueError:
                fail(f"{where}: uid '{uid}' is not valid hex")
            if uid_bytes in seen:
                fail(f"{where}: duplicate uid {uid}")
            seen.add(uid_bytes)
            if not (1 <= len(sid) <= STUDENT_ID_MAX) or not printable_ascii(sid):
                fail(f"{where}: student_id must be 1..{STUDENT_ID_MAX} ASCII characters")
            if not (1 <= len(name) <= NAME_MAX) or not printable_ascii(name):
                fail(f"{where}: name '{name}' must be 1..{NAME_MAX} ASCII characters")
            rows.append((uid_bytes, sid, name))
    rows.sort(key=lambda r: (len(r[0]), r[0]))
    return rows


def write(rows, path):
    out = [
        "/* GENERATED by tools/gen_students.py from tools/students.csv. DO NOT EDIT. */",
        '#include "students.h"',
        "",
        "/* Sorted by (uid_len, uid) for students_lookup(). */",
        "const student_t g_students[] = {",
    ]
    for uid, sid, name in rows:
        padded = list(uid) + [0] * (7 - len(uid))
        uid_c = ", ".join(f"0x{b:02X}" for b in padded)
        out.append(f"    {{ {len(uid)}U, {{ {uid_c} }}, {c_string(sid)}, {c_string(name)} }},")
    if not rows:
        out.append("    { 0U, { 0 }, \"\", \"\" },  /* placeholder: empty CSV */")
    out += [
        "};",
        "",
        f"const uint16_t g_student_count = {len(rows)}U;",
        "",
    ]
    with open(path, "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(out))


def main():
    if len(sys.argv) != 3:
        fail("usage: gen_students.py <students.csv> <students_table.c>")
    rows = load(sys.argv[1])
    write(rows, sys.argv[2])
    print(f"gen_students.py: {len(rows)} students -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
